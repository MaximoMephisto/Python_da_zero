# For and While loops
for i in range(0,11): # Loop from 0 to 10
    print(i)

for i in range(0, 11, 2): #Loop from 0 to 10 width step of 2
    print(i)

for i in range(1, 5): # Loop with increment of 2
    i = i * 2 
    print(i)

print("End for loop")

# While loop with increment
a = 0
b = 5
while (a < b):
    print(a)
    a += 1

print("End while loop")

